"""Rewrite the baseline migration (0001) from the ORM models.

Use this ONLY while 0001 is the single revision and no stamped database you
care about was built from an older copy of it: that is, during the work that
introduced Alembic, when tables were still being added to ``db.py``. A database
created before the regeneration and stamped 0001 will not gain the new tables.
Once 0001 has shipped, never run this again. Add a new revision instead:

    chanakya db revision -m "what changed" --rev-id 0002

Usage: python scripts/regenerate_baseline.py
The output is deterministic, so running it on unchanged models changes nothing.
"""

from __future__ import annotations

import sys
import tempfile
from pathlib import Path

from chanakya import migrate
from chanakya.db import make_engine

NOTE = (
    "\nThe schema as it stood when Alembic was introduced: every table that\n"
    "``Base.metadata.create_all`` produced. A database built that way is adopted\n"
    "with ``chanakya db stamp`` and never runs this script.\n\n"
    "String columns are VARCHAR(n) on SQLite and unbounded TEXT on PostgreSQL\n"
    "(see ``chanakya.db.String``). Generated by ``scripts/regenerate_baseline.py``\n"
    "(autogenerate against an empty SQLite database); ``tests/test_migrations.py``\n"
    "fails if it drifts from the models.\n"
)


def main() -> int:
    versions = migrate.MIGRATIONS_DIR / "versions"
    others = [p.name for p in versions.glob("*.py") if p.name not in ("__init__.py", "0001_baseline.py")]
    if others:
        print(f"refusing: later revisions exist ({', '.join(sorted(others))}). Add a new revision instead.")
        return 1
    target = versions / "0001_baseline.py"
    previous = target.read_text(encoding="utf-8") if target.exists() else None
    target.unlink(missing_ok=True)
    migrate._script.cache_clear()
    with tempfile.TemporaryDirectory() as scratch:
        engine = make_engine(f"sqlite:///{Path(scratch) / 'empty.db'}")
        try:
            migrate.new_revision(engine, "baseline", autogenerate=True, rev_id=migrate.BASELINE_REVISION)
        finally:
            engine.dispose()
    quotes = '"' * 3
    head, body = target.read_text(encoding="utf-8").split(quotes + "\n", 1)
    # A fixed date keeps the file identical when the models have not changed.
    head = "\n".join("Created: 2026-10-10" if line.startswith("Created:") else line for line in head.split("\n"))
    body = body.replace("    # ### commands auto generated by Alembic - please adjust! ###\n", "")
    body = body.replace("    # ### end Alembic commands ###\n", "")
    text = head + NOTE + quotes + "\n" + body
    target.write_text(text, encoding="utf-8", newline="\n")
    print("unchanged" if text == previous else f"rewrote {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
