"""Render docs/04_WAYAM_CAPABILITY_MATRIX.md from config/wayam_capabilities.yaml
(the YAML is the source of truth; re-run after editing it)."""

from __future__ import annotations

from pathlib import Path

from chanakya.pipeline.knowledge import load_knowledge_base

ROOT = Path(__file__).resolve().parents[1]

INTRO = """# 04 — Wayam Capability Matrix

Source of truth: [`config/wayam_capabilities.yaml`](../config/wayam_capabilities.yaml) (machine-readable,
editable without code changes; `chanakya capabilities validate` checks it). This page is generated by
`scripts/render_capability_matrix.py`.

Research basis: www.wayam.ai pages fetched on **2026-10-10** — home, Arjuna, industries, public sector,
healthcare, about, and the Vakyam, Wayam Eye, Raksha, Vedha, Sutradhar, Pariksha, Drishti, Setu and
Santulan accelerator pages. `/ourportfolio` returned only a video page (marked `noindex`). The other
accelerators (Nirmiti, Sahay, Sanchay, Purti, Sankalp, Vahana, Yukti, Niyojan, Anvaya, Shilpa, Sama,
Tatvam, Bodham, Parivart) are described from their cards on the homepage; their own pages were not
fetched, so those capabilities carry medium confidence at most.

## Verified facts vs. hypotheses

| Hypothesis from the brief | Finding | Treatment |
|---|---|---|
| A. Agentic AI / multi-agent / workflow automation | Verified: multi-agent systems over MCP with orchestrator, governance, observability | Existing offering (high) |
| B. Arjuna CCTV analytics | Verified: detection, tracking, counting, zone intrusion, loitering/dwell, crowd density, vehicle classification, parking occupancy, low light, on-prem, redaction; safety compliance via pose estimation | Existing (high) |
| B. ANPR | **Not stated** — site shows vehicle classification and plate *redaction*, not plate reading | Custom build (low) |
| C. Vakyam voice | Verified: dialer/CCaaS integration, transcription, intent/sentiment, agent assist, 100% QA, CRM/lake sync | Existing (high); Indian-language coverage unverified |
| D. Healthcare RCM / claims / prior auth | **Not found**. Raksha covers healthcare compliance/security/clinical-AI oversight (HIPAA, SOC 2, ISO 27001, HITRUST) | Raksha existing (medium); RCM custom build (low) |
| E. WayamEye solar | Verified: drone/thermal imagery, hotspots, soiling, cracks, PID, string anomalies, work orders | Existing (high) |
| F. Mining | **No dedicated offering**; Drishti (industrial operations console) and Arjuna safety are adjacent | Custom build (low) |
| G. Testing, security testing, modernisation, BI, IT ops | Verified: Pariksha (AI testing), Vedha (authorised pentest), Setu (BI migration), Sutradhar (AIOps), Data/AI CoE foundation; app modernisation only as engineering foundation (Nirmiti) | Mostly existing; modernisation custom |

Not published anywhere on the site, therefore **unknown** to Chanakya: turnover, years in operation,
team size, certifications (ISO/CMMI/CERT-In), MSME/DPIIT status, and any Indian government project.
The homepage logo strip is captioned as organisations *the team* has worked with (GE, Daimler, Optum,
Koch, Schneider Electric, Dassault Systèmes, Mahindra, Wabtec, Motorola Solutions) — none are Indian
government bodies, and Chanakya does not use them as references. Use cases on accelerator pages are
labelled "representative scenario" and are not treated as deployments.

## Capability table

| ID | Capability | Offering | Status | Confidence | Typical government buyers | Evidence |
|---|---|---|---|---|---|---|
"""


def main() -> None:
    kb = load_knowledge_base(ROOT / "config" / "wayam_capabilities.yaml")
    out = [INTRO]
    for c in kb.capabilities:
        ev = " · ".join(f"[{u.split('wayam.ai')[-1] or '/'}]({u})" for u in c.evidence_urls)
        out.append(f"| {c.id} | {c.name} | {c.offering} | {c.offering_status.replace('_', ' ')} | {c.confidence} | "
                   f"{', '.join(c.departments[:4])} | {ev} |\n")
    out.append("\n## Capability details\n")
    for c in kb.capabilities:
        kw = c.keywords
        out.append(f"""
### {c.id} — {c.name}

- **Offering:** {c.offering} · **Status:** {c.offering_status.replace('_', ' ')} · **Confidence:** {c.confidence}
- **Description:** {' '.join(c.description.split())}
- **Project types:** {', '.join(c.project_types)}
- **Relevant departments:** {', '.join(c.departments)}
- **Technologies (as stated):** {', '.join(c.technologies) or '—'}
- **Strong keywords:** {', '.join(kw.strong)}
- **Supporting keywords:** {', '.join(kw.medium)}
- **Context-only keywords:** {', '.join(kw.weak) or '—'}
- **Negative / exclusion phrases:** {', '.join(c.negative) or '—'}
- **Example procurement requirements:** {' · '.join(c.example_requirements)}
- **Matching indicators:** {'; '.join(c.matching_indicators) or '—'}
- **Exclusion indicators:** {'; '.join(c.exclusion_indicators) or '—'}
- **Evidence:** {', '.join(c.evidence_urls)}
""" + (f"- **Note:** {c.notes}\n" if c.notes else ""))
    out.append("\n## Global rules\n\n")
    out.append(f"- **Exclusion terms ({len(kb.global_.exclusion_terms)}):** reject a notice when one appears in the title "
               "and no strong capability phrase is present (e.g. civil works, toll/user fee, housekeeping, catering, "
               "tyres, lattice tower, selection of developer).\n")
    out.append(f"- **Technology signals ({len(kb.global_.tech_signals)}):** keep a notice for free semantic scoring even "
               "without capability keywords (high-recall net).\n")
    out.append(f"- **Synonyms ({len(kb.global_.synonyms)}):** abbreviation expansion (AI, CCTV, ANPR, VAPT, SOC, HMIS, BESS…), "
               "counted once per concept.\n")
    out.append("\nEditing guidance: add phrases buyers actually use; put words that also appear in unrelated work under "
               "`weak`; record new proof (a won contract, a certification) in `company_facts` and the config "
               "`company_profile` — never in keywords. Every edit changes `kb_version`, which re-scores affected notices "
               "on the next run.\n")
    (ROOT / "docs" / "04_WAYAM_CAPABILITY_MATRIX.md").write_text("".join(out), encoding="utf-8")
    print("wrote docs/04_WAYAM_CAPABILITY_MATRIX.md")


if __name__ == "__main__":
    main()
