"""Run the Chanakya pipeline (rules + semantics, no paid LLM) over the real notices
observed on official portals on 2026-10-10 and write a decision table.

Usage: python scripts/validate_live_snapshot.py [--out docs/validation/LIVE_SNAPSHOT_2026-10-10.md]
"""

from __future__ import annotations

import argparse
import tempfile
from pathlib import Path

import yaml
from sqlalchemy import select

from chanakya.app import run_pipeline
from chanakya.config import SourceConfig, load_settings
from chanakya.db import Opportunity, init_db, make_engine, session_factory
from chanakya.timeutil import format_ist

ROOT = Path(__file__).resolve().parents[1]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=ROOT / "docs" / "validation" / "LIVE_SNAPSHOT_2026-10-10.md")
    args = ap.parse_args()
    rows = yaml.safe_load((ROOT / "tests/fixtures/benchmark/labeled_tenders.yaml").read_text())["records"]
    live = [r for r in rows if str(r.get("origin", "")).startswith("live:")]
    tmp = Path(tempfile.mkdtemp(prefix="chanakya_live_"))
    src = tmp / "src"
    src.mkdir()
    (src / "live.yaml").write_text(yaml.safe_dump({"records": [{**r, "evidence": f"{r['origin']} — observed 2026-10-10"} for r in live]}))
    s = load_settings(ROOT / "config" / "chanakya.example.yaml")
    s.app.database_url = f"sqlite:///{tmp / 'live.db'}"
    s.app.reports_dir = tmp / "reports"
    s.app.inbox_dir = tmp / "inbox"
    s.llm.mode = "disabled"
    s.sources = [SourceConfig(id="live_snapshot", type="fixture", path=src)]
    s.filtering.backfill_days = 3650
    engine = make_engine(s.app.database_url)
    init_db(engine)
    session = session_factory(engine)()
    res = run_pipeline(s, session, export=True)
    by_title = {o.title: o for o in session.scalars(select(Opportunity))}
    lines = [
        "# Live snapshot validation — notices observed on 2026-10-10",
        "",
        "Real notices copied (listing-level fields) from official sites on 2026-10-10 and run through Chanakya's "
        "deterministic stages (rules + lexical semantics + scoring). **No LLM was used** (`llm.mode: disabled`), so "
        "AI triage would only add a cheap verdict on the CANDIDATE rows. Labels are the Chanakya team's judgement. "
        "Notices that had already closed on 2026-10-10 are marked expired and are kept to show that relevant-but-"
        "closed opportunities are detected yet never surfaced as actionable.",
        "",
        f"Generated by `scripts/validate_live_snapshot.py`; workbook: `{res.report_path.name if res.report_path else 'n/a'}`.",
        "",
        "| # | Notice (as published) | Source (observed 2026-10-10) | Our label | Decision | Priority / score | Top capability | Status | Why |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    correct = 0
    for i, r in enumerate(live, 1):
        o = by_title.get(r["title"])
        if o is None:
            continue
        surfaced = o.filter_decision in ("candidate", "strong")
        ok = surfaced == (r["label"] == "relevant")
        correct += ok
        cap = (o.top_capabilities or [{}])[0].get("id", "—") if o.filter_decision != "rejected" else "—"
        why = "; ".join((o.filter_reasons or [])[:2]).replace("|", "/")
        lines.append(f"| {i} | {r['title'][:110]} | {r['origin'].removeprefix('live:')} | {r['label']} | "
                     f"{o.filter_decision}{'' if ok else ' ⚠'} | {o.priority} / {o.relevance_score:.0f} | {cap} | {o.status} | {why[:160]} |")
    lines += ["", f"Agreement with labels (surfaced = candidate/strong): **{correct}/{len(live)}**.", "",
              f"Closing dates are shown on the source; e.g. the NTPC REL drone-thermography rate contract closed "
              f"{format_ist(next((o.closing_at for t, o in by_title.items() if 'Drone Thermography' in t), None))}.",
              "", "Source links: https://eprocure.gov.in/cppp/latestactivetendersnew/cpppdata · "
              "https://eprocure.gov.in/cppp/highvaluetenders · https://eprocure.gov.in/eprocure/app · "
              "https://etenders.gov.in/eprocure/app · https://www.becil.com/tenders?page=4 · "
              "https://ntpctender.ntpc.co.in/NITDetails/NITs/29853 · https://www.goa.gov.in/wp-content/uploads/2026/06/ITG-NIT-837.pdf"]
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
